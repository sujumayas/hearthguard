"""Writes dashboards/names.js from scripts/data/class_defs.gd.

Run from the repo root after changing class skills or talents:
    python3 dashboards/gen_names.py
"""
import json
import re

out = {}
cls = None
for line in open("scripts/data/class_defs.gd"):
    m = re.match(r'^\t"([a-z_]+)": \{$', line)
    if m:
        cls = m.group(1)
        out[cls] = {"skills": [], "talents": {}}
        continue
    if not cls:
        continue
    m = re.search(r'"key": "([QWER])", "id": "[^"]+", "name": "([^"]+)"', line)
    if m:
        out[cls]["skills"].append(f"{m.group(2)} ({m.group(1)})")
        continue
    m = re.search(r'\{"id": "([^"]+)", "name": "([^"]+)", "desc": "([^"]+)"', line)
    if m:
        out[cls]["talents"][m.group(1)] = f"{m.group(2)}: {m.group(3)}"

with open("dashboards/names.js", "w") as f:
    f.write("// Skill and talent names per class. Generated by dashboards/gen_names.py.\n")
    f.write("const NAMES = " + json.dumps(out, indent=1) + ";\n")
